// Builds card/src/core/icons.js from Lucide (ISC licence). Each icon's shapes become one path, on Lucide's 24-unit grid.
// Run by hand when the list changes: node card/tools/gen-icons.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dirs = ['node_modules/lucide-static/icons', 'node_modules/lucide-static/dist/icons'].map((d) => join(root, d));
const dir = dirs.find(existsSync);
if (!dir) throw new Error('lucide-static icons not found');

const NAMES =
  `phone smartphone mail globe map-pin message-circle clock calendar user users building building-2 store shopping-bag shopping-cart
  star heart check award badge-check briefcase scale calculator stethoscope activity pill cross scissors sparkles flower-2 gem shirt utensils coffee cake
  chef-hat home key ruler pencil-ruler hammer wrench camera image video palette code-xml laptop cpu car truck plane graduation-cap book-open leaf sun
  zap link send qr-code arrow-right circle square hexagon wallet indian-rupee landmark dumbbell`
    .split(/\s+/)
    .filter(Boolean);

const attrs = (s) => Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const n = (v) => Number(v ?? 0);

function shapeToPath(tag, a) {
  if (tag === 'path') return a.d;
  if (tag === 'line') return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
  if (tag === 'polyline' || tag === 'polygon') {
    const pts = a.points
      .trim()
      .split(/[\s,]+/)
      .map(Number);
    let d = `M${pts[0]} ${pts[1]}`;
    for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
    return tag === 'polygon' ? `${d}Z` : d;
  }
  if (tag === 'circle' || tag === 'ellipse') {
    const rx = n(a.r ?? a.rx);
    const ry = n(a.r ?? a.ry);
    const cx = n(a.cx);
    const cy = n(a.cy);
    return `M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}Z`;
  }
  if (tag === 'rect') {
    const x = n(a.x);
    const y = n(a.y);
    const w = n(a.width);
    const h = n(a.height);
    const r = Math.min(n(a.rx ?? a.ry), w / 2, h / 2);
    if (!r) return `M${x} ${y}H${x + w}V${y + h}H${x}Z`;
    return `M${x + r} ${y}H${x + w - r}A${r} ${r} 0 0 1 ${x + w} ${y + r}V${y + h - r}A${r} ${r} 0 0 1 ${x + w - r} ${y + h}H${x + r}A${r} ${r} 0 0 1 ${x} ${y + h - r}V${y + r}A${r} ${r} 0 0 1 ${x + r} ${y}Z`;
  }
  throw new Error(`Unhandled shape: ${tag}`);
}

const out = {};
const missing = [];
for (const name of NAMES) {
  const file = join(dir, `${name}.svg`);
  if (!existsSync(file)) {
    missing.push(name);
    continue;
  }
  const svg = readFileSync(file, 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  out[name] = [...inner.matchAll(/<(path|line|polyline|polygon|circle|ellipse|rect)\b([^>]*)\/?>/g)]
    .map((m) => shapeToPath(m[1], attrs(m[2])))
    .join('');
}
const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n');
writeFileSync(
  join(root, 'card/src/core/icons.js'),
  `// Generated by card/tools/gen-icons.mjs from Lucide (ISC licence, https://lucide.dev). Don't edit by hand.\nexport const ICONS = {\n${body}\n};\n`,
);
console.log(`${Object.keys(out).length} icons written${missing.length ? `; missing: ${missing.join(', ')}` : ''}`);
